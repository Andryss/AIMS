package gov.mib.aims.backend.model;

/**
 * Рассмотрение заявки и фактическое заключение субъекта.
 */
public enum DetentionRequestStatus {

    /** Новая заявка. */
    NEW,
    /** Заявка принята, ожидается прибытие субъекта. */
    ACCEPTED,
    /** Субъект находится под стражей. */
    IN_CUSTODY,
    /** Субъект освобождён. */
    RELEASED,
    /** Надзиратель отклонил заявку. */
    REJECTED,
    /** Заявка отменена до помещения под стражу. */
    CANCELLED
}
